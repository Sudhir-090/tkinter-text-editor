import tkinter as tf
import ttkthemes as ttt
import winsound as ws
aaa=tf.Tk()
aaa.title("text saver 3000")
aaa.geometry("750x450")
aaa.configure(bg="light blue")
aaa.iconbitmap("Text.ico")
def savet():
    ask.place_forget()
    asr.place_forget()
    ase.place_forget()
    ss=tf.Label(aaa,text="enter the name of the file",font=("Arial",15),bg="light blue")
    ss.pack()
    ss.place(x=280,y=150)
    ss2=tf.Label(aaa,text="*note=This file will be save where you have this program",font=("Arial",9),bg="light blue")
    ss2.pack()
    ss2.place(x=0,y=0)
    ent=tf.Entry(aaa,width=40,font=("Arial",10))
    ent.pack()
    ent.place(x=280,y=180)
    def cancel():
        ent.destroy()
        ent2.destroy()
        ent3.destroy()
        ss.destroy()
        ss2.destroy()
        ask.place(x=0,y=0)
        asr.place(x=610,y=0)
        ase.place(x=610,y=60)
    ent3=tf.Button(aaa,text="cancel",width=8,font=("arial",8),command=cancel)
    ent3.pack()
    ent3.place(x=435,y=212,)
    def save():
        ws.Beep(1000,100)
        name=ent.get()+".txt"
        file=open(name,"w+")
        file.write(ask.get("1.0","end-1c"))
    ent2=tf.Button(aaa,text="save",width=8,font=("arial",8),command=save)
    ent2.pack()
    ent2.place(x=385,y=225,anchor="center")
ask=tf.Text(aaa,width=40,font=("Arial",20),height=13)
asr=tf.Button(aaa,text="save it",width=10,font=("Arial",15),command=savet)
asr.pack()
asr.place(x=610,y=0)
ask.place(x=0,y=0)
def clear():
    ask.delete("1.0","end-1c")
ase=tf.Button(text="clear all",width=10,font=("Arial",15),command=clear)
ase.pack()
ase.place(x=610,y=60)
aaa.mainloop()